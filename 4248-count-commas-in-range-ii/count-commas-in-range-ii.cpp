class Solution {
public:
    long long countCommas(long long n) {
        if(n < 1000){
            return 0;
        }
        else if(n >= 1000 && n < 1000000){
            return n - 999;
        }
        else if(n >= 1000000 && n < 1000000000){
            return (999999 - 999) + 2*(n - 999999);
        }
        else if(n >= 1000000000 && n < 1000000000000){
            return (999999 - 999) + 2*(999999999 - 999999) + 3*(n - 999999999);
        }
        else if(n >= 1000000000000 && n < 1000000000000000){
            return (999999 - 999) + 2*(999999999 - 999999) + 3*(999999999999 - 999999999) + 4*(n - 999999999999);
        }
        else{
            return (999999 - 999) + 2*(999999999 - 999999) + 3*(999999999999 - 999999999) + 4*(999999999999999 - 999999999999) + 5;
        }
    }
};